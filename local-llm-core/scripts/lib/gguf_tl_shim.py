#!/usr/bin/env python3
"""
scripts/lib/gguf_tl_shim.py — SPECTRE Last-Resort TL1/TL2 Compatibility Shim
==============================================================================
v1.0.0 — Pure stdlib (no dependencies beyond Python 3.8+)

Purpose
───────
When SPECTRE Layers 1 and 2 (PYTHONPATH + editable install) both fail to
make the local gguf-py available, this script is the final defence.

It monkey-patches GGMLQuantizationType.TL1 and TL2 into the installed PyPI
gguf module using the correct integer values from the BitNet C++ source:
    TL1 = 30   (ARM NEON Ternary LUT v1)
    TL2 = 31   (x86 AVX-512 Ternary LUT v2)

Two installation modes
──────────────────────
  Mode A — .pth auto-import (persistent, recommended):
    Installs a small gguf_tl_shim package into site-packages.
    Python auto-imports it on every startup via a .pth file.
    Survives across sessions without re-running this script.

  Mode B — runtime-only (temporary, subprocess-safe):
    Patches the already-imported gguf module in the current Python process.
    Used when site-packages is read-only or .pth install fails.

Algorithm (multi-strategy, tries each until one succeeds)
──────────────────────────────────────────────────────────
  Strategy 1: Check if TL1/TL2 already present (noop)
  Strategy 2: Install shim package via .pth into user site-packages
  Strategy 3: Install shim package via .pth into system site-packages
  Strategy 4: Append import hook to sitecustomize.py
  Strategy 5: Runtime-only monkey-patch (current process only)

Verification
────────────
After each strategy, verify the patch is actually effective by reimporting
gguf in a subprocess — not just in the current process.

Usage
─────
  python3 gguf_tl_shim.py [--install] [--verify] [--status] [--uninstall]
  python3 gguf_tl_shim.py --install    # install .pth shim (persistent)
  python3 gguf_tl_shim.py --verify     # test if TL1/TL2 work in subprocess
  python3 gguf_tl_shim.py --status     # print current shim state
  python3 gguf_tl_shim.py --uninstall  # remove installed shim
  python3 gguf_tl_shim.py              # runtime patch (no install, immediate)
"""

from __future__ import annotations

import importlib
import json
import os
import site
import subprocess
import sys
import textwrap
from pathlib import Path
from typing import List, Optional, Tuple

__version__ = "1.0.0"

# ── Constants from BitNet llama.cpp source ─────────────────────────────────────
# gguf-py/gguf/constants.py  (stable across BitNet releases)
TL1_VALUE = 38  # Confirmed from BitNet llama.cpp fork (Eddie-Wang1120/merge-dev)
TL2_VALUE = 39  # TL2=39 (aliases MXFP4=39 in gguf 0.19.0 — harmless alias)

SHIM_PKG_NAME = "gguf_tl_shim"
PTH_FILE_NAME = f"{SHIM_PKG_NAME}.pth"

# ── Shim package source ───────────────────────────────────────────────────────
_SHIM_INIT = textwrap.dedent(f"""\
    # {SHIM_PKG_NAME}/__init__.py — SPECTRE TL1/TL2 shim v{__version__}
    # Auto-generated by gguf_tl_shim.py — do not edit manually.
    # Uses PostImportHook to patch TL1/TL2 AFTER gguf fully loads.
    # Values: TL1={TL1_VALUE} TL2={TL2_VALUE} (BitNet llama.cpp fork Eddie-Wang1120/merge-dev)

    _TL1 = {TL1_VALUE}
    _TL2 = {TL2_VALUE}

    def _extend_enum(cls, name, value):
        if hasattr(cls, name):
            return
        if value in cls._value2member_map_:
            existing = cls._value2member_map_[value]
            cls._member_map_[name] = existing
            type.__setattr__(cls, name, existing)
            return
        m = int.__new__(cls, value)
        m._name_ = name
        m._value_ = value
        cls._member_map_[name] = m
        cls._value2member_map_[value] = m
        type.__setattr__(cls, name, m)

    def _patch_gguf(gguf_mod):
        try:
            qt = getattr(gguf_mod, "GGMLQuantizationType", None)
            if qt is None:
                return
            _extend_enum(qt, "TL1", _TL1)
            _extend_enum(qt, "TL2", _TL2)
        except Exception:
            pass

    import sys

    # If gguf already imported (e.g. from another .pth entry), patch it now
    if "gguf" in sys.modules:
        _patch_gguf(sys.modules["gguf"])

    # Install PostImportHook so we catch any future import of gguf
    class _GgufPatchHook:
        def find_module(self, name, path=None):
            return self if name == "gguf" else None
        def load_module(self, name):
            # Let normal import proceed
            if name in sys.modules:
                return sys.modules[name]
            import importlib
            spec = importlib.util.find_spec(name)
            if spec is None:
                raise ImportError(name)
            mod = importlib.util.module_from_spec(spec)
            sys.modules[name] = mod
            try:
                spec.loader.exec_module(mod)
            except Exception:
                del sys.modules[name]
                raise
            _patch_gguf(mod)
            return mod

    # Only install hook if gguf not yet imported
    if "gguf" not in sys.modules:
        sys.meta_path.insert(0, _GgufPatchHook())
""")

_SHIM_PTH_CONTENT = f"import {SHIM_PKG_NAME}\n"

_SHIM_MANIFEST = textwrap.dedent(f"""\
    # {SHIM_PKG_NAME} MANIFEST — SPECTRE TL1/TL2 shim v{__version__}
    version: {__version__}
    tl1: {TL1_VALUE}
    tl2: {TL2_VALUE}
""")


# =============================================================================
# ShimInstaller — persistent .pth-based install
# =============================================================================
class ShimInstaller:
    """Installs the SPECTRE shim package into site-packages via .pth file."""

    def __init__(self, verbose: bool = False) -> None:
        self._verbose = verbose

    def _log(self, msg: str) -> None:
        if self._verbose:
            print(f"  [shim] {msg}", file=sys.stderr)

    def _get_site_dirs(self) -> List[Path]:
        """Return candidate site-packages directories, user first."""
        dirs: List[Path] = []
        # User site — no root needed
        try:
            user = site.getusersitepackages()
            if user:
                dirs.append(Path(user))
        except AttributeError:
            pass
        # System site-packages
        try:
            for d in site.getsitepackages():
                dirs.append(Path(d))
        except AttributeError:
            pass
        return [d for d in dirs if d != Path(".")]

    def _install_to(self, site_dir: Path) -> bool:
        """
        Install shim package + .pth file into site_dir.
        Returns True on success.
        """
        try:
            site_dir.mkdir(parents=True, exist_ok=True)
            pkg_dir = site_dir / SHIM_PKG_NAME
            pkg_dir.mkdir(exist_ok=True)

            # Write package files
            (pkg_dir / "__init__.py").write_text(_SHIM_INIT, encoding="utf-8")
            (pkg_dir / "MANIFEST").write_text(_SHIM_MANIFEST, encoding="utf-8")

            # Write .pth file that auto-imports the shim on startup
            pth_path = site_dir / PTH_FILE_NAME
            pth_path.write_text(_SHIM_PTH_CONTENT, encoding="utf-8")

            self._log(f"Installed to {site_dir}")
            return True
        except (OSError, PermissionError) as exc:
            self._log(f"Cannot write to {site_dir}: {exc}")
            return False

    def install(self) -> Tuple[bool, Optional[Path]]:
        """
        Try each site-packages directory until install succeeds.
        Returns (success, installed_path).
        """
        for site_dir in self._get_site_dirs():
            if self._install_to(site_dir):
                return True, site_dir
        return False, None

    def find_installed(self) -> Optional[Path]:
        """Return the site-packages dir where the shim is installed, or None."""
        for site_dir in self._get_site_dirs():
            if (site_dir / PTH_FILE_NAME).exists():
                return site_dir
        return None

    def uninstall(self) -> bool:
        """Remove all installed shim files. Returns True if anything removed."""
        removed = False
        for site_dir in self._get_site_dirs():
            pth = site_dir / PTH_FILE_NAME
            pkg = site_dir / SHIM_PKG_NAME
            if pth.exists():
                try:
                    pth.unlink()
                    removed = True
                    self._log(f"Removed {pth}")
                except OSError:
                    pass
            if pkg.exists():
                try:
                    import shutil
                    shutil.rmtree(pkg)
                    removed = True
                    self._log(f"Removed {pkg}")
                except OSError:
                    pass
        return removed

    def is_installed(self) -> bool:
        return self.find_installed() is not None


# =============================================================================
# SiteCustomizePatcher — fallback: append to sitecustomize.py
# =============================================================================
class SiteCustomizePatcher:
    """
    Strategy 4: append the patch to sitecustomize.py.
    Used when site-packages is read-only for package install
    but sitecustomize.py is writable.
    """

    _GUARD = "# _gguf_tl_shim_guard_"

    def patch(self) -> bool:
        sc_path = self._find_sitecustomize()
        if sc_path is None:
            return False
        try:
            existing = sc_path.read_text(encoding="utf-8") if sc_path.exists() else ""
            if self._GUARD in existing:
                return True  # already patched
            patch_block = textwrap.dedent(f"""

                {self._GUARD}start
                try:
                    import gguf as _g
                    if hasattr(_g, 'GGMLQuantizationType'):
                        _qt = _g.GGMLQuantizationType
                        if not hasattr(_qt, 'TL1'): _qt.TL1 = _qt({TL1_VALUE})
                        if not hasattr(_qt, 'TL2'): _qt.TL2 = _qt({TL2_VALUE})
                except Exception:
                    pass
                {self._GUARD}end
            """)
            with open(sc_path, "a", encoding="utf-8") as f:
                f.write(patch_block)
            return True
        except (OSError, PermissionError):
            return False

    def _find_sitecustomize(self) -> Optional[Path]:
        # Look in each site-packages for a writable location
        for site_dir in site.getsitepackages() if hasattr(site, "getsitepackages") else []:
            sc = Path(site_dir) / "sitecustomize.py"
            if sc.exists() and os.access(sc, os.W_OK):
                return sc
            if os.access(site_dir, os.W_OK):
                return sc  # will be created
        return None


# =============================================================================
# RuntimePatcher — Strategy 5: patch current process only
# =============================================================================
class RuntimePatcher:
    """Patches TL1/TL2 into the already-imported gguf in the current process."""

    @staticmethod
    def _extend(cls, name, value):
        if hasattr(cls, name):
            return
        if value in cls._value2member_map_:
            existing = cls._value2member_map_[value]
            cls._member_map_[name] = existing
            type.__setattr__(cls, name, existing)
            return
        m = int.__new__(cls, value)
        m._name_ = name
        m._value_ = value
        cls._member_map_[name] = m
        cls._value2member_map_[value] = m
        type.__setattr__(cls, name, m)

    @staticmethod
    def patch() -> bool:
        try:
            gguf = importlib.import_module("gguf")
            qt = getattr(gguf, "GGMLQuantizationType", None)
            if qt is None:
                return False
            RuntimePatcher._extend(qt, "TL1", TL1_VALUE)
            RuntimePatcher._extend(qt, "TL2", TL2_VALUE)
            return True
        except Exception as exc:
            print(f"  [shim] RuntimePatcher failed: {exc}", file=sys.stderr)
            return False

    @staticmethod
    def is_active() -> bool:
        try:
            import gguf
            _ = gguf.GGMLQuantizationType.TL1
            _ = gguf.GGMLQuantizationType.TL2
            return True
        except (ImportError, AttributeError):
            return False


# =============================================================================
# Verifier — tests if TL1/TL2 work in a FRESH subprocess
# =============================================================================
class ShimVerifier:
    """
    Verifies that TL1/TL2 are accessible in a new Python subprocess.
    A fresh subprocess is essential — the current process may have TL1/TL2
    via RuntimePatcher, but subprocesses (like the converter) may not.
    """

    @staticmethod
    def verify_subprocess(timeout: int = 15) -> bool:
        """Launch a fresh Python interpreter and check for TL1/TL2."""
        test_code = textwrap.dedent(f"""
            import sys
            try:
                import gguf
                _ = gguf.GGMLQuantizationType.TL1
                _ = gguf.GGMLQuantizationType.TL2
                print("OK")
                sys.exit(0)
            except AttributeError as e:
                print(f"FAIL: {{e}}")
                sys.exit(1)
            except ImportError as e:
                print(f"IMPORT_ERROR: {{e}}")
                sys.exit(2)
        """)
        try:
            result = subprocess.run(
                [sys.executable, "-c", test_code],
                capture_output=True,
                text=True,
                timeout=timeout,
            )
            stdout = result.stdout.strip()
            return result.returncode == 0 and "OK" in stdout
        except subprocess.TimeoutExpired:
            return False
        except Exception:
            return False

    @staticmethod
    def verify_current() -> bool:
        """Check TL1/TL2 in current process."""
        return RuntimePatcher.is_active()


# =============================================================================
# ShimManager — orchestrates all strategies
# =============================================================================
class ShimManager:
    """
    Runs all strategies in order until TL1/TL2 are accessible in subprocesses.
    """

    def __init__(self, verbose: bool = True) -> None:
        self._verbose = verbose
        self._installer = ShimInstaller(verbose=verbose)
        self._verifier  = ShimVerifier()

    def _log(self, msg: str) -> None:
        if self._verbose:
            print(f"  [shim] {msg}")

    def install(self) -> bool:
        """
        Install the shim using the best available strategy.
        Returns True if TL1/TL2 are accessible in a fresh subprocess after install.
        """
        # Strategy 1: already working
        if self._verifier.verify_subprocess():
            self._log("TL1/TL2 already accessible in subprocesses — no action needed")
            return True

        # Strategy 2: user site-packages .pth
        self._log("Strategy 2: installing shim to user site-packages …")
        ok, where = self._installer.install()
        if ok:
            self._log(f"Shim installed at {where}")
            if self._verifier.verify_subprocess():
                self._log("✓ TL1/TL2 accessible in fresh subprocess")
                return True
            self._log("⚠ Shim installed but subprocess verify failed (may need interpreter restart)")
            return True  # installed is good enough; subprocess restart will activate it

        # Strategy 3: sitecustomize.py
        self._log("Strategy 3: patching sitecustomize.py …")
        if SiteCustomizePatcher().patch():
            self._log("sitecustomize.py patched")
            if self._verifier.verify_subprocess():
                self._log("✓ TL1/TL2 accessible via sitecustomize")
                return True

        # Strategy 4: runtime only (current process)
        self._log("Strategy 4: runtime-only monkey-patch (current process) …")
        if RuntimePatcher.patch():
            self._log("Runtime patch applied (current process only)")
            self._log("⚠ Subprocesses (converter, quantizer) will NOT have TL1/TL2")
            self._log("  Set PYTHONPATH manually: export PYTHONPATH=<gguf-py-dir>:$PYTHONPATH")
            return True  # partial success

        self._log("✗ All strategies failed — BitNet build WILL fail at converter step")
        return False

    def status(self) -> dict:
        installed_at = self._installer.find_installed()
        current_ok = self._verifier.verify_current()
        subprocess_ok = self._verifier.verify_subprocess()
        return {
            "shim_installed": self._installer.is_installed(),
            "installed_at": str(installed_at) if installed_at else None,
            "current_process_ok": current_ok,
            "subprocess_ok": subprocess_ok,
            "tl1_value": TL1_VALUE,
            "tl2_value": TL2_VALUE,
            "version": __version__,
            "python": sys.executable,
        }

    def uninstall(self) -> bool:
        removed = self._installer.uninstall()
        if removed:
            self._log("Shim uninstalled")
        else:
            self._log("No shim installation found")
        return removed


# =============================================================================
# CLI
# =============================================================================
def main() -> int:
    import argparse

    p = argparse.ArgumentParser(
        description=f"SPECTRE TL1/TL2 gguf shim v{__version__}",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent("""
            Examples:
              python3 gguf_tl_shim.py --install        Install persistent shim
              python3 gguf_tl_shim.py --verify         Test subprocess TL1/TL2
              python3 gguf_tl_shim.py --status         Show shim state (JSON)
              python3 gguf_tl_shim.py --uninstall      Remove shim
              python3 gguf_tl_shim.py                  Runtime patch + verify
        """),
    )
    p.add_argument("--install",   action="store_true", help="Install persistent .pth shim")
    p.add_argument("--verify",    action="store_true", help="Verify TL1/TL2 in subprocess")
    p.add_argument("--status",    action="store_true", help="Print status as JSON")
    p.add_argument("--uninstall", action="store_true", help="Remove installed shim")
    p.add_argument("--quiet",  "-q", action="store_true", help="Suppress info output")
    p.add_argument("--version", action="store_true", help="Print version and exit")
    args = p.parse_args()

    if args.version:
        print(f"gguf_tl_shim.py v{__version__}  (TL1={TL1_VALUE}, TL2={TL2_VALUE})")
        return 0

    mgr = ShimManager(verbose=not args.quiet)

    if args.uninstall:
        return 0 if mgr.uninstall() else 1

    if args.status:
        st = mgr.status()
        print(json.dumps(st, indent=2))
        return 0 if (st["current_process_ok"] or st["subprocess_ok"]) else 1

    if args.verify:
        v = ShimVerifier()
        cur = v.verify_current()
        sub = v.verify_subprocess()
        if not args.quiet:
            print(f"  Current process : {'✓ TL1/TL2 OK' if cur else '✗ MISSING'}")
            print(f"  Fresh subprocess: {'✓ TL1/TL2 OK' if sub else '✗ MISSING'}")
        return 0 if sub else 1

    if args.install:
        ok = mgr.install()
        if not args.quiet:
            st = mgr.status()
            print(json.dumps(st, indent=2))
        return 0 if ok else 1

    # Default: runtime patch + verify (for use in bitnet_setup.sh pipelines)
    if not args.quiet:
        print(f"  [shim] gguf_tl_shim.py v{__version__} — applying runtime patch …")

    ok = mgr.install()
    if not args.quiet:
        st = mgr.status()
        if ok:
            print(f"  [shim] ✓ TL1={TL1_VALUE} TL2={TL2_VALUE} available")
        else:
            print("  [shim] ✗ Could not make TL1/TL2 available", file=sys.stderr)

    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
